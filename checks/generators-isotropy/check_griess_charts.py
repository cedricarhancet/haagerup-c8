#!/usr/bin/env python3
"""Exact projective-chart degree counts and the case-II reflection hyperplane.
Run with --source-dir pointing to calculs-sources/cas-II (or an isolated copy).
This verifies finite polynomial data regenerated by the original VOA engine;
it does not independently verify that engine.
"""
import argparse, itertools, json, os, sys
from pathlib import Path
import sympy as sp
ap=argparse.ArgumentParser();ap.add_argument('--source-dir',required=True);ap.add_argument('--output',required=True);a=ap.parse_args()
source=Path(a.source_dir).resolve();out=Path(a.output).resolve();sys.path.insert(0,str(source));os.chdir(source)
import griess_subalgebras as GS
result={}
for case in ['I','II']:
    _, basis, prod, gram=GS.griess_data(case);m=len(basis)-1;x=sp.symbols('x0:'+str(m));lam=sp.Symbol('lam')
    q=[sp.expand(sum(x[i]*x[j]*prod[i+1,j+1][k+1] for i in range(m) for j in range(m))) for k in range(m)]
    charts=[]
    for k in range(m):
        sub={x[j]:0 for j in range(k)};sub[x[k]]=1;vs=[*x[k+1:],lam]
        eq=[sp.expand((q[j]-lam*x[j]).subs(sub)) for j in range(m)]
        gb=sp.groebner(eq,*vs,order='lex',domain=sp.QQ)
        if list(gb)==[1]: dim=0;standard=[]
        else:
            assert gb.is_zero_dimensional
            lms=[tuple(p.LM(order=gb.order).exponents) for p in gb.polys]
            bounds=[]
            for j in range(len(vs)):
                powers=[m_[j] for m_ in lms if m_[j]>0 and all(m_[i]==0 for i in range(len(vs)) if i!=j)]
                assert powers;bounds.append(min(powers))
            standard=[t for t in itertools.product(*(range(n) for n in bounds)) if not any(all(a>=b for a,b in zip(t,lm)) for lm in lms)]
            dim=len(standard)
        charts.append({'first_nonzero_coordinate':k,'variables':[str(v) for v in vs], 'groebner_basis':[str(p.as_expr()) for p in gb.polys], 'quotient_dimension':dim,'standard_monomial_exponents':standard})
    given=json.loads((source/'griess_subalgebras.json').read_text())[case]['subalgebras'];points=[]
    for d in given:
        xv=[sp.sympify(z) for z in d['x']];lv=sp.sympify(d['lambda']);ss=dict(zip(x,xv));ss[lam]=lv
        assert all(sp.simplify((q[j]-lam*x[j]).subs(ss))==0 for j in range(m))
        first=next(i for i,z in enumerate(xv) if z!=0);normalized=[sp.simplify(z/xv[first]) for z in xv]
        assert not any(all(sp.simplify(u-v)==0 for u,v in zip(normalized,p)) for p in points)
        points.append(normalized)
    assert len(points)==sum(c['quotient_dimension'] for c in charts)
    entry={'dimension_B':m+1,'number_of_distinct_solutions':len(points),'charts':charts}
    if case=='II':
        G=sp.Matrix(gram);fixed=[2,3,6,7,11,12,13];H=sp.Matrix.hstack(*(sp.Matrix([0]+[sp.sympify(z) for z in given[i]['x']]) for i in fixed))
        assert H.rank()==3 and all(H[4,j]==0 for j in range(H.cols))
        detH=G[1:4,1:4].det();assert detH!=0
        entry['fixed_hyperplane_gram']=[[str(G[i,j]) for j in range(1,4)] for i in range(1,4)]
        entry['fixed_hyperplane_determinant']=str(detH)
    result[case]=entry
    print(case,len(points),[c['quotient_dimension'] for c in charts],flush=True)
out.write_text(json.dumps({'status':'PASS','checks':result},indent=2)+'\n')
