"""Axis E: scale-free coupling invariants of the weight-two data (case II, subalgebra 9), exact over K.
For primary lines u_tau (highest weight), N_tau = <u_tau, theta u_tau> (theta u = lowest weight vector obtained by
the fixed lowering word f'^a f''^b), and for types tau, sigma, rho with rho - tau a weight of V(sigma):
   T = < (u_tau)_(1) w', theta u_rho >,   w' = the vector of weight rho - tau in the module of u_sigma (fixed word),
   I(tau, sigma, rho) = T^2 / (N_tau N_sigma N_rho).
I is invariant under rescaling of the lines and under isomorphisms restricting to inner automorphisms on U_1;
hence (i) an isomorphism between the algebras generated by two choices preserves I; (ii) if U is unitary, an
antilinear automorphism maps highest weight vectors to multiples of lowest weight vectors and I is real.
Complex conjugation q -> -q maps the choice 0 to the choice 1."""
import sys, json, time
import sympy as sp
from gmpy2 import mpq
import lattice_voa as V, cases as C, closure_explore as CE, Kfield as K
def kform(terms_a, terms_b):
    s = K.Z
    for a, va in terms_a:
        for b, vb in terms_b:
            f = V.form(va, vb)
            if f: s = K.add(s, K.scal(f, K.mul(a, b)))
    return s
def kprod_terms(terms_u, n, terms_w):
    out = []
    for a, va in terms_u:
        for b, vb in terms_w:
            r = V.clean(V.mode_vec(va, n, vb))
            if r: out.append((K.mul(a, b), r))
    return out
def kinv(a):
    # inverse in K via norm: multiply by conjugates
    c1 = (a[0], -a[1], a[2], -a[3])          # r -> -r
    c2 = (a[0], a[1], -a[2], -a[3])          # q -> -q
    c3 = (a[0], -a[1], -a[2], a[3])          # both
    n = K.mul(K.mul(a, c1), K.mul(c2, c3))
    assert all(x == 0 for x in n[1:]), n
    return K.scal(1/n[0], K.mul(K.mul(c1, c2), c3))
if __name__ == '__main__':
    chi = int(sys.argv[1]) if len(sys.argv) > 1 else 0
    t0 = time.time()
    T, D, out, types, N1, N2, s13, U1, A2 = CE.setup('II', 9)
    info = json.load(open('closure_explore_II_9.json')); Lj = json.load(open('isotropic_lines_II_9.json'))
    tl = sorted(types); choice = info['combos'][chi]
    lines = {tau: [[K.from_sympy(c) for c in sp.sympify(l)] for l in Lj[str(tau)][0]['lines']] for tau in tl}
    MT = {}
    for tau, l in zip(tl, choice):
        ty = types[tau]; lv = lines[tau][l]; res = []
        for w in range(len(ty['mods'][0][0])):
            terms = []
            for k in range(ty['d']):
                if ty['mods'][k][0][w]: terms.append((lv[k], ty['mods'][k][0][w]))
                if ty['mods'][k][1][w]: terms.append((K.mul(lv[k], K.R), ty['mods'][k][1][w]))
            res.append(terms)
        MT[tau] = res
    def widx(tau, mu):
        """index of the module vector of weight mu = (m1, m2) in the lowering order"""
        a, b = tau; m1, m2 = mu
        if (a - m1) % 2 or (b - m2) % 2 or abs(m1) > a or abs(m2) > b: return None
        i = (a - m1)//2; j = (b - m2)//2
        return i*(b + 1) + j
    N = {tau: kform(MT[tau][0], MT[tau][-1]) for tau in tl}
    print('norms N_tau (components on 1, r, q, rq):')
    for tau in tl: print('  ', tau, [str(x) for x in N[tau]])
    res = []
    for tau in tl:
        for sigma in tl:
            for rho in tl:
                mu = (rho[0] - tau[0], rho[1] - tau[1])
                w = widx(sigma, mu)
                if w is None: continue
                Tval = kform(kprod_terms(MT[tau][0], 1, MT[sigma][w]), MT[rho][-1])
                if K.iszero(Tval): continue
                I = K.mul(K.mul(Tval, Tval), kinv(K.mul(K.mul(N[tau], N[sigma]), N[rho])))
                res.append({'tau': str(tau), 'sigma': str(sigma), 'rho': str(rho), 'I': [str(x) for x in I],
                            'real': I[2] == 0 and I[3] == 0, 'Icomplex': str(K.to_complex(I))})
        print('  tau', tau, 'done (%.0fs)' % (time.time() - t0), flush=True)
    nonreal = [r for r in res if not r['real']]
    print('nonzero couplings:', len(res), '; invariants not in Q(sqrt13) (non-real):', len(nonreal))
    for r in (nonreal or res)[:6]: print('  ', r['tau'], r['sigma'], r['rho'], r['Icomplex'])
    json.dump({'choice': choice, 'norms': {str(t): [str(x) for x in N[t]] for t in tl}, 'invariants': res}, open(f'invariants_K_{chi}.json', 'w'), indent=1)
    print('time %.0fs' % (time.time() - t0))
