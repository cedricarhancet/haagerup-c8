"""Axis A1-A2: B = Com_{V'}(A)_2 and its Griess algebra, in cases I and II.
A = affine VOA generated by U_1 = g' + g''.  B = {v in V'_2 : x_n v = 0 for x in U_1, n >= 0}.
Product a.b = a_1 b (commutative since Com_{V'}(A)_1 = 0); unit e = omega_C / 2."""
import sys, time, json
from gmpy2 import mpq
from flint import fmpq_mat, fmpq
import lattice_voa as V, cases as C, linalg as LA
def U1_basis(T): return [T[k] for k in ('H1', 'e1', 'f1', 'H2', 'e2', 'f2')]
def weight_space(T, wt, mu):
    return [k for k in V.basis(wt) if C.weight_of_key(T, k) == mu]
def annihilated(T, wt, mu, ns=(0, 1, 2)):
    """vectors of V'_wt of joint weight mu annihilated by x_n, x in U_1, n in ns"""
    W = weight_space(T, wt, mu)
    rows_cols = []
    for x in U1_basis(T):
        for n in ns:
            if wt - n < 0: continue
            rows_cols.append([V.clean(V.mode_vec(x, n, {k: mpq(1)})) for k in W])
    # stack: each block gives columns over its own keys
    keys = sorted(set().union(*[set(c) for blk in rows_cols for c in blk]))
    kidx = {(b, k): i for i, (b, k) in enumerate((b, k) for b in range(len(rows_cols)) for k in keys)}
    M = fmpq_mat(len(rows_cols)*len(keys), len(W))
    for b, blk in enumerate(rows_cols):
        for j, col in enumerate(blk):
            for k, x in col.items():
                M[kidx[(b, k)], j] = LA.to_fq(x)
    ns_ = LA.nullspace(M)
    return [V.clean({W[j]: LA.to_mq(v[j]) for j in range(len(W)) if v[j] != 0}) for v in ns_], len(W)
def sugawara(T, which):
    H, e, f = (T['H1'], T['e1'], T['f1']) if which == 1 else (T['H2'], T['e2'], T['f2'])
    k = C.CASES[T['case']]['levels'][which - 1]
    # Casimir with normalized form (H,H)=2, (e,f)=1 : H^2/2 + e f + f e ; omega = Cas/(2(k+2))
    out = {}
    V.vadd(out, V.mode_vec(H, -1, H), mpq(1, 2))
    V.vadd(out, V.mode_vec(e, -1, f)); V.vadd(out, V.mode_vec(f, -1, e))
    return V.clean({kk: x/(2*(k + 2)) for kk, x in out.items()})
if __name__ == '__main__':
    res = {}
    for case in sys.argv[1:] or ['I', 'II']:
        t0 = time.time()
        T = C.build(case); T['case'] = case
        Bv, dW = annihilated(T, 2, (0, 0))
        wA = {}
        V.vadd(wA, sugawara(T, 1)); V.vadd(wA, sugawara(T, 2))
        omC = V.clean(V.vadd(dict(V.OMEGA), wA, -1))
        print('case', case, ': dim of the joint weight-zero space of V\'_2 =', dW, '; dim B =', len(Bv))
        assert LA.coords(Bv, omC) is not None, 'omega_C not in B'
        # Griess structure constants in a basis starting with omega_C
        basis = [omC] + [b for b in Bv]
        # extract a basis containing omC
        M, keys = LA.matrix_from_cols(basis)
        Rr, r = M.rref()
        piv = []
        for i in range(r):
            piv.append(next(j for j in range(M.ncols()) if Rr[i, j] != 0))
        basis = [basis[j] for j in piv]
        n = len(basis)
        print('   basis of B with omega_C first; Griess products ...')
        St = {}
        for i in range(n):
            for j in range(i, n):
                p = V.clean(V.mode_vec(basis[i], 1, basis[j]))
                cc = LA.coords(basis, p)
                assert cc is not None, 'product not in B'
                St[(i, j)] = cc
        # commutativity check
        for i in range(n):
            for j in range(i):
                p = V.clean(V.mode_vec(basis[i], 1, basis[j]))
                assert LA.coords(basis, p) == St[(j, i)], 'not commutative'
        gram = [[V.form(basis[i], basis[j]) for j in range(n)] for i in range(n)]
        print('   omega_C . omega_C =', [str(x) for x in St[(0, 0)]], '; <omega_C, omega_C> =', gram[0][0], '(c_C/2)')
        print('   time %.1fs' % (time.time() - t0))
        res[case] = {'basis': [{repr(k): str(v) for k, v in b.items()} for b in basis],
                     'struct': {f'{i},{j}': [str(x) for x in v] for (i, j), v in St.items()},
                     'gram': [[str(x) for x in row] for row in gram]}
    json.dump(res, open('commutant_griess.json', 'w'))
