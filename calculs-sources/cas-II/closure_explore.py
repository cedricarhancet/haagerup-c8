"""Axis B4 (exploration, floating point): pairwise closure conditions for the finitely many choices of lines
p_tau (output of isotropic_lines.py).  For u in p_tau (highest weight) and w' in the g'+g''-module of v in p_sigma:
   (a) u_2 w' in U_1,
   (b) u_1 w' in U2max = A_2 + C_2 + sum_rho module(E_rho)   (necessary, independent of the other choices),
   (c) u_1 w' in U_2(choice) for a full choice of lines (triple condition).
By the generation argument (V(tau) (x) V(sigma) is generated by u (x) V(sigma)) and skew symmetry, unordered
pairs suffice.  Residuals are computed by least squares in the monomial basis; exact certification is done in
closure_certify.py."""
import sys, json, time, itertools
import numpy as np
import sympy as sp
from gmpy2 import mpq
import lattice_voa as V, isotropic_lines as IL, commutant_griess as CG, griess_subalgebras as GS
S = sp.sqrt(13)
def split_vec(Ecol, P):
    """E column (Q(sqrt13) coefficients on the basis P) -> (rational vector, rational vector)"""
    vp, vq = {}, {}
    for i, z in enumerate(Ecol):
        z = sp.expand(sp.radsimp(z))
        q = z.coeff(S) if z.has(S) else 0; p = sp.expand(z - q*S)
        if p: V.vadd(vp, P[i], mpq(int(sp.Rational(p).p), int(sp.Rational(p).q)))
        if q: V.vadd(vq, P[i], mpq(int(sp.Rational(q).p), int(sp.Rational(q).q)))
    return V.clean(vp), V.clean(vq)
def lowerings(T, tau, v):
    out = []
    a = v
    for i in range(tau[0] + 1):
        b = a
        for j in range(tau[1] + 1):
            out.append(b)
            b = V.clean(V.mode_vec(T['f2'], 0, b))
        a = V.clean(V.mode_vec(T['f1'], 0, a))
    return out
class Num:
    def __init__(self, wt):
        self.keys = V.basis(wt); self.idx = {k: i for i, k in enumerate(self.keys)}
    def vec(self, v, scale=1.0):
        x = np.zeros(len(self.keys), dtype=complex)
        for k, c in v.items(): x[self.idx[k]] += complex(c)*scale
        return x
def residual(Bmat, z):
    if not np.any(z): return 0.0
    sol, *_ = np.linalg.lstsq(Bmat, z, rcond=None)
    return float(np.linalg.norm(Bmat @ sol - z)/max(1.0, np.linalg.norm(z)))
def setup(case, ci):
    D, out = IL.admissible_spaces(case, ci)
    T = D['T']
    N1, N2 = Num(1), Num(2)
    s13 = float(np.sqrt(13))
    types = {}
    for tau, v in out.items():
        assert len(v['spaces']) == 1, 'several admissible eigenspaces: extend the script'
        spc = v['spaces'][0]
        L = IL.lines_in(spc)
        assert isinstance(L, list)
        E = spc['E']; d = E.shape[1]
        parts = [split_vec(list(E[:, k]), v['P']) for k in range(d)]
        lines = [[complex(sp.N(c, 30)) for c in l] for l in L]
        mods = [[lowerings(T, tau, p) for p in pq] for pq in parts]      # mods[k][0|1][weight index]
        types[tau] = {'parts': parts, 'lines': lines, 'mods': mods, 'd': d, 'h': (str(spc['h1']), str(spc['h2']))}
    # U_1, A_2, C_2
    U1 = CG.U1_basis(T)
    A2 = []
    for x in U1:
        A2.append(V.clean(V.mode_vec(x, -2, {V.VAC: mpq(1)})))
        for y in U1: A2.append(V.clean(V.mode_vec(x, -1, y)))
    return T, D, out, types, N1, N2, s13, U1, A2
def combine(N, parts_vecs, coefs, s13):
    """sum_k coef_k (p_k + sqrt13 q_k)"""
    x = np.zeros(len(N.keys), dtype=complex)
    for (p, q), c in zip(parts_vecs, coefs):
        x += c*(N.vec(p) + s13*N.vec(q))
    return x
if __name__ == '__main__':
    case, ci = sys.argv[1], int(sys.argv[2])
    t0 = time.time()
    T, D, out, types, N1, N2, s13, U1, A2 = setup(case, ci)
    G = json.load(open('griess_subalgebras.json'))[case]['subalgebras'][ci]
    _, basis, _, _ = GS.griess_data(case)
    xv = [0] + [complex(sp.N(sp.sympify(c), 30)) for c in G['x']]
    e_num = N2.vec(basis[0]); x_num = sum((xv[i]*N2.vec(basis[i]) for i in range(1, len(basis))), np.zeros(len(N2.keys), dtype=complex))
    U1m = np.array([N1.vec(u) for u in U1]).T
    A2m = np.array([N2.vec(a) for a in A2]).T
    tl = sorted(types)
    # numeric module vectors for every line: lines[tau][l] = list of numeric vectors over weights
    linemods = {}
    for tau in tl:
        ty = types[tau]
        L = []
        for l in ty['lines']:
            nw = len(ty['mods'][0][0])
            vecs = []
            for w in range(nw):
                vecs.append(sum((l[k]*(N2.vec(ty['mods'][k][0][w]) + s13*N2.vec(ty['mods'][k][1][w])) for k in range(ty['d'])), np.zeros(len(N2.keys), dtype=complex)))
            L.append(vecs)
        linemods[tau] = L
    # U2max
    cols = [A2m, e_num[:, None], x_num[:, None]]
    for tau in tl:
        ty = types[tau]
        for k in range(ty['d']):
            for w in range(len(ty['mods'][k][0])):
                cols.append((N2.vec(ty['mods'][k][0][w]) + s13*N2.vec(ty['mods'][k][1][w]))[:, None])
    U2max = np.hstack(cols)
    print('rank A_2 =', np.linalg.matrix_rank(A2m), '; rank U2max =', np.linalg.matrix_rank(U2max))
    # pairwise products: u (hw of tau, line l) acting on module vectors of (sigma, line m)
    # exact rational products of the split parts, cached
    cache = {}
    def prod_num(tau, k, s, sigma, k2, s2, w, n):
        key = (tau, k, s, sigma, k2, s2, w, n)
        if key not in cache:
            a = types[tau]['parts'][k][s]; b = types[sigma]['mods'][k2][s2][w]
            r = V.clean(V.mode_vec(a, n, b))
            cache[key] = (N1 if n == 2 else N2).vec(r)
        return cache[key]
    def products(tau, l, sigma, m, n):
        lu = types[tau]['lines'][l]; lv = types[sigma]['lines'][m]
        nw = len(types[sigma]['mods'][0][0])
        res = []
        for w in range(nw):
            z = 0
            for k in range(types[tau]['d']):
                for k2 in range(types[sigma]['d']):
                    c = lu[k]*lv[k2]
                    pp = prod_num(tau, k, 0, sigma, k2, 0, w, n); pq = prod_num(tau, k, 0, sigma, k2, 1, w, n)
                    qp = prod_num(tau, k, 1, sigma, k2, 0, w, n); qq = prod_num(tau, k, 1, sigma, k2, 1, w, n)
                    z = z + c*(pp + 13*qq + s13*(pq + qp))
            res.append(z)
        return res
    pair_ok = {}
    report = []
    for i, tau in enumerate(tl):
        for sigma in tl[i:]:
            for l in range(len(types[tau]['lines'])):
                for m in range(len(types[sigma]['lines'])):
                    ra = max(residual(U1m, z) for z in products(tau, l, sigma, m, 2))
                    rb = max(residual(U2max, z) for z in products(tau, l, sigma, m, 1))
                    pair_ok[(tau, l, sigma, m)] = (ra < 1e-8 and rb < 1e-8)
                    report.append((str(tau), l, str(sigma), m, '%.2e' % ra, '%.2e' % rb))
            print('pair', tau, sigma, 'done (%.0fs)' % (time.time() - t0), flush=True)
    # self-consistency per type (same type, same line) and full combinations
    good_lines = {tau: [l for l in range(len(types[tau]['lines'])) if pair_ok[(tau, l, tau, l)]] for tau in tl}
    print('lines passing the self-product test:', {str(t): v for t, v in good_lines.items()})
    combos = []
    for choice in itertools.product(*[good_lines[t] for t in tl]):
        ok = True
        for i, tau in enumerate(tl):
            for j in range(i, len(tl)):
                if not pair_ok[(tau, choice[i], tl[j], choice[j])]: ok = False; break
            if not ok: break
        if ok: combos.append(choice)
    print('full choices passing all pairwise tests (a), (b):', len(combos))
    json.dump({'report': report, 'good_lines': {str(t): v for t, v in good_lines.items()}, 'combos': combos,
               'h': {str(t): types[t]['h'] for t in tl}}, open(f'closure_explore_{case}_{ci}.json', 'w'), indent=1)
    print('time %.0fs' % (time.time() - t0))
