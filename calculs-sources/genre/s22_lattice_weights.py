"""Axis G1/G3 (v12). Exact lattice facts behind the genus theorem.
(1) For both cases, the h-weights (m',m'') = ((H',beta),(H'',beta)) of the roots beta of E6+A2 (which generate the
    lattice E6+A2, hence all h-weights of V' = V_{E6+A2}) satisfy m' = m'' mod 2: the group Gamma(V') of h-weights of V'
    is contained in Gamma_0 = {m' = m'' mod 2}; we also record that it is equal to Gamma_0.
(2) The lattice L = Gamma_0^* (dual for B((a,b),(c,d)) = ac/(2k') + bd/(2k'')) is L_{k',k''} = <(2k',0),(k',k'')>;
    Gram matrices, reduced binary forms, discriminant forms.
(3) O(L) (all isometries, proper and improper) and its image in O(L'/L); surjectivity onto O(L'/L).
(4) The isometries L_II'/L_II -> L_I'/L_I (there are four)."""
import sys, os, json, itertools
from fractions import Fraction as Fr
HERE = os.path.abspath(os.path.dirname(__file__)); GF = os.path.abspath(HERE + '/../generation-forte')
sys.path.insert(0, GF); os.chdir(GF)
import lattice_voa as V, cases as C
out = {}
LEV = {'I': (1, 39), 'II': (3, 13)}
for case in ('I', 'II'):
    T = C.build(case)
    W = sorted(set((int(C.hval(T['c1'], b)), int(C.hval(T['c2'], b))) for b in V.ROOTS))
    par = all((a - b) % 2 == 0 for a, b in W)
    # the group generated by the root weights
    import sympy as sp
    M = sp.Matrix(W)
    H = M.T.tolist()
    # Hermite normal form of the Z-span (2 x n)
    from sympy.matrices.normalforms import hermite_normal_form
    hnf = hermite_normal_form(sp.Matrix(W).T)
    out[case] = {'root_weights': W, 'all_m1_equiv_m2_mod2': par, 'span_hnf': [list(map(int, r)) for r in hnf.tolist()]}
    print(case, 'levels', LEV[case], 'root weights:', len(W), 'parity condition:', par, 'span HNF:', hnf.tolist())

def B(k, u, v): return Fr(u[0]*v[0], 2*k[0]) + Fr(u[1]*v[1], 2*k[1])
res = {}
for case, k in LEV.items():
    b1, b2 = (2*k[0], 0), (k[0], k[1])         # basis of L = Gamma_0^*
    G = [[B(k, b1, b1), B(k, b1, b2)], [B(k, b2, b1), B(k, b2, b2)]]
    det = G[0][0]*G[1][1] - G[0][1]**2
    # check L = Gamma_0^*: Gamma_0 = <(2,0),(1,1)>
    g1, g2 = (2, 0), (1, 1)
    dualok = all(B(k, x, y).denominator == 1 for x in (b1, b2) for y in (g1, g2))
    # index [Gamma_0^* : L] via determinants: det(Gamma_0) * det(L) should be 1
    Gg = [[B(k, g1, g1), B(k, g1, g2)], [B(k, g2, g1), B(k, g2, g2)]]
    detg = Gg[0][0]*Gg[1][1] - Gg[0][1]**2
    a, bb, c = int(G[0][0]), int(2*G[0][1]), int(G[1][1])     # form a x^2 + b xy + c y^2 (Gram/2 convention below)
    res[case] = {'gram': [[int(x) for x in r] for r in G], 'det': int(det), 'L_is_dual_of_Gamma0': dualok and det*detg == 1,
                 'min_norm': min(int(G[0][0]*x*x + 2*G[0][1]*x*y + G[1][1]*y*y) for x in range(-5, 6) for y in range(-5, 6) if (x, y) != (0, 0))}
    print(case, 'Gram', res[case]['gram'], 'det', int(det), 'L = Gamma_0^*:', res[case]['L_is_dual_of_Gamma0'], 'min norm', res[case]['min_norm'])

# discriminant forms, O(L), image in O(L'/L)
def disc(Gm):
    import sympy as sp
    Gs = sp.Matrix(Gm); Gi = Gs.inv(); d = int(Gs.det())
    # L'/L cyclic of order d (det squarefree 39): generator = a column of Gi giving an element of order d
    elems = []
    for x in range(d):
        for y in range(d):
            v = Gi*sp.Matrix([x, y])
            elems.append((Fr(int(sp.fraction(v[0])[0]), int(sp.fraction(v[0])[1])), Fr(int(sp.fraction(v[1])[0]), int(sp.fraction(v[1])[1]))))
    return Gs, Gi, d
def norm(Gm, v): return Gm[0][0]*v[0]*v[0] + 2*Gm[0][1]*v[0]*v[1] + Gm[1][1]*v[1]*v[1]
def isometries(Gm, R=12):
    """all integer matrices g with g^T G g = G (columns = images of basis vectors)"""
    n0, n1 = Gm[0][0], Gm[1][1]
    c0 = [v for v in itertools.product(range(-R, R + 1), repeat=2) if norm(Gm, v) == n0]
    c1 = [v for v in itertools.product(range(-R, R + 1), repeat=2) if norm(Gm, v) == n1]
    out = []
    for u in c0:
        for w in c1:
            ip = Gm[0][0]*u[0]*w[0] + Gm[0][1]*(u[0]*w[1] + u[1]*w[0]) + Gm[1][1]*u[1]*w[1]
            if ip == Gm[0][1] and abs(u[0]*w[1] - u[1]*w[0]) == 1: out.append((u, w))
    return out
iso_res = {}
for case in ('I', 'II'):
    Gm = res[case]['gram']; d = res[case]['det']
    # L'/L: generator gamma = G^{-1} e_j with order d; q(x gamma) = x^2 q(gamma) mod 1
    import sympy as sp
    Gi = sp.Matrix(Gm).inv()
    gens = []
    for j in range(2):
        v = Gi[:, j]
        den = sp.ilcm(*[sp.fraction(x)[1] for x in v])
        gens.append((v, int(den)))
    v, den = max(gens, key=lambda t: t[1])
    assert den == d
    qg = Fr(int(sp.fraction((v.T*sp.Matrix(Gm)*v)[0]/2)[0]), int(sp.fraction((v.T*sp.Matrix(Gm)*v)[0]/2)[1]))
    O_q = [u for u in range(d) if (u*u - 1) % d == 0]
    isos = isometries(Gm)
    images = set()
    for (u, w) in isos:
        g = sp.Matrix([[u[0], w[0]], [u[1], w[1]]])
        gv = g*v
        # gv = m v mod L
        for m in range(d):
            diff = gv - m*v
            if all(sp.fraction(x)[1] == 1 for x in diff): images.add(m); break
    iso_res[case] = {'q_generator': str(qg), 'O_q': O_q, 'O_L_order': len(isos), 'image_of_O_L': sorted(images),
                     'surjective': sorted(images) == O_q}
    print(case, 'q(gen) =', qg, 'O(q) = mult. by', O_q, '|O(L)| =', len(isos), 'image', sorted(images), 'surjective:', sorted(images) == O_q)
# isometries of discriminant forms II -> I: x -> u x with q_I(u g_I) = q_II(g_II)
qI = Fr(iso_res['I']['q_generator']); qII = Fr(iso_res['II']['q_generator'])
isoms = [u for u in range(39) if __import__('math').gcd(u, 39) == 1 and (Fr(u*u)*qI - qII).denominator == 1]
print('isometries L_II\'/L_II -> L_I\'/L_I (u with q_I(u g_I) = q_II(g_II)):', isoms)
# reduced forms of discriminant -39 (as in s20) for the record
red = sorted((a, b, c) for a in range(1, 8) for b in range(-a + 1, a + 1) for c in range(a, 40)
             if b*b - 4*a*c == -39 and (abs(b) <= a <= c) and not (b < 0 and (abs(b) == a or a == c)))
print('reduced forms of discriminant -39:', red)
json.dump({'parity': out, 'lattices': res, 'orthogonal_groups': iso_res, 'isometries_II_to_I': isoms, 'reduced_forms_disc_-39': red},
          open(HERE + '/s22_lattice_weights.json', 'w'), indent=1)

# (5) action of the Weyl group elements w' = diag(-1,1), w'' = diag(1,-1) of U_1 (in (m',m'') coordinates) on
#     Gamma_0 / L = L'/L, generated by (1,1): w(1,1) = u (1,1) mod L
def in_L(k, v):
    a, c = v
    return a % k[0] == 0 and c % k[1] == 0 and ((a//k[0]) - (c//k[1])) % 2 == 0
weyl = {}
for case, k in LEV.items():
    assert not in_L(k, (1, 1)) and all(not in_L(k, (n, n)) for n in range(1, 39)) and in_L(k, (39, 39))
    act = {}
    for name, w in (("w'", (-1, 1)), ("w''", (1, -1)), ('-1', (-1, -1))):
        img = (w[0], w[1])
        u = next(u for u in range(39) if in_L(k, (img[0] - u, img[1] - u)))
        act[name] = u
    weyl[case] = act
    print(case, 'Weyl action on L\'/L = Z/39 (generator (1,1)):', act)
d = json.load(open(HERE + '/s22_lattice_weights.json')); d['weyl_action_on_discriminant'] = weyl
json.dump(d, open(HERE + '/s22_lattice_weights.json', 'w'), indent=1)
