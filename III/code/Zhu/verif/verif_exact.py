"""SECOND VERIFIER (written separately from z4x.py, with its own arithmetic routines and its own reduction strategy).

Input : rows_exact.pkl (the 19981 exact projected relations, generators of the ideal I_K)
        upper_exact.pkl (output of z4x.py: killed vertices, linear eliminations, rewriting rules)
        specfib/z4_upper_algebra_modp.pkl (output of the modular program of Article I run on the reduced exact rows)
Checks, all exact over K = Q(r, q), r^2 = 13, q^2 = -3 (basis 1, r, q, rq):
 A. compatibility with the order (longer paths larger; equal length: lexicographically smaller tuple larger) and
    with the endpoints, for every rule and every linear elimination;
 B. every generator of I_K reduces to 0 (so that I_K is contained in the ideal J' generated by the rewriting data);
 C. every overlap ambiguity of the rules resolves;  D. every inclusion ambiguity resolves;
 E. no leading word contains an eliminated arrow or an arrow at a killed vertex, and the eliminations of arrows at
    killed vertices reduce to 0 (ambiguities between eliminations, vertex kills and rules);
 F. counts of irreducible paths by length;  G. integrality at the prime p and unit leading coefficients;
 H. comparison of the reductions modulo the prime with the rules of the modular program of Article I.
The reduction strategy (leftmost occurrence first, then shortest leading word) differs from the one of z4x.py.
Output: verif_exact.json."""
import pickle, json, sys, time
from gmpy2 import mpq
t0 = time.time()
def log(*a): print(*a, '(%.0fs)' % (time.time() - t0), flush=True)
ZE = '/home/claude/hj/work/Calculs/zhu-exact'
P = 8388571; S13 = 1649360; S3 = 2036966
assert S13 * S13 % P == 13 and (S3 * S3 + 3) % P == 0
# ---------------- own arithmetic in K (tuples of four rationals) ----------------
def kz(t): return t[0] == 0 and t[1] == 0 and t[2] == 0 and t[3] == 0
def kadd(x, y): return (x[0] + y[0], x[1] + y[1], x[2] + y[2], x[3] + y[3])
def kmul(x, y):
    a, b, c, d = x; e, f, g, h = y
    # (a + b r + c q + d rq)(e + f r + g q + h rq), r^2 = 13, q^2 = -3, (rq)^2 = -39
    return (a*e + 13*b*f - 3*c*g - 39*d*h,
            a*f + b*e - 3*c*h - 3*d*g,
            a*g + c*e + 13*b*h + 13*d*f,
            a*h + d*e + b*g + c*f)
KONE = (mpq(1), mpq(0), mpq(0), mpq(0)); KMONE = (mpq(-1), mpq(0), mpq(0), mpq(0))
def kconv(t): return tuple(mpq(x) for x in t)
def den_prime_to_p(t): return all(int(x.denominator) % P != 0 for x in t)
def kred(t):
    vals = []
    for x in t:
        n, d = int(x.numerator), int(x.denominator)
        vals.append(n % P * pow(d, -1, P) % P)
    return (vals[0] + vals[1] * S13 + vals[2] * S3 + vals[3] * S13 * S3) % P
def acc(out, w, c):
    if w in out:
        s = kadd(out[w], c)
        if kz(s): del out[w]
        else: out[w] = s
    elif not kz(c): out[w] = c
# ---------------- data ----------------
D = pickle.load(open(ZE + '/rows_exact.pkl', 'rb'))
AR = D['ARROWS']
U = pickle.load(open(ZE + '/upper_exact.pkl', 'rb'))
KILLED = set(U['killed']); ACTIVE = set(U['active']); VERTS = set(U['verts'])
RULES = {q: {w: kconv(c) for w, c in r.items()} for q, r in U['rules'].items()}
ELIM = {a: {w: kconv(c) for w, c in r.items()} for a, r in U['alllin'].items()}
def s_(a): return AR[a]['source']
def t_(a): return AR[a]['target']
def ends(w, ep): return ep if w == () else (t_(w[0]), s_(w[-1]))
def composable(w): return all(s_(w[i]) == t_(w[i + 1]) for i in range(len(w) - 1))
log('rules', len(RULES), 'eliminations', len(ELIM), 'killed', sorted(KILLED), 'active', len(ACTIVE))
res = {}
# ---------------- A. order and endpoints ----------------
def smaller(w, q):          # w strictly smaller than q in the order (q is the leading word)
    return len(w) < len(q) or (len(w) == len(q) and w > q)
badA = 0
for q, r in RULES.items():
    ep = (t_(q[0]), s_(q[-1]))
    if not composable(q): badA += 1
    for w in r:
        if not smaller(w, q) or (w != () and (not composable(w) or ends(w, ep) != ep)) or (w == () and ep[0] != ep[1]): badA += 1
for a, r in ELIM.items():
    ep = (t_(a), s_(a))
    for w in r:
        if not smaller(w, (a,)) or (w != () and ends(w, ep) != ep) or (w == () and ep[0] != ep[1]): badA += 1
res['A_order_endpoint_violations'] = badA; log('A', badA)
# ---------------- normal form ----------------
LEADS_BY_FIRST = {}
for q in RULES: LEADS_BY_FIRST.setdefault(q[0], []).append(q)
for k in LEADS_BY_FIRST: LEADS_BY_FIRST[k].sort(key=len)
memo = {}
def nf_word(w, ep):
    """normal form of the path w (w = () is the vertex idempotent of ep), as a dict word -> coefficient"""
    key = (w, ep if w == () else None)
    if key in memo: return memo[key]
    if w == ():
        out = {} if ep[0] in KILLED else {(): KONE}
        memo[key] = out; return out
    if any(s_(a) in KILLED or t_(a) in KILLED for a in w):
        memo[key] = {}; return {}
    out = None
    for i, a in enumerate(w):                 # eliminated arrows first, leftmost
        if a in ELIM:
            out = {}
            e = ends(w, None)
            for u, c in ELIM[a].items():
                for v, d in nf_word(w[:i] + u + w[i + 1:], e).items(): acc(out, v, kmul(c, d))
            break
    if out is None:
        for i in range(len(w)):               # leftmost occurrence, then shortest leading word
            for q in LEADS_BY_FIRST.get(w[i], ()):
                if w[i:i + len(q)] == q:
                    out = {}
                    e = ends(w, None)
                    for u, c in RULES[q].items():
                        for v, d in nf_word(w[:i] + u + w[i + len(q):], e).items(): acc(out, v, kmul(c, d))
                    break
            if out is not None: break
    if out is None: out = {w: KONE}
    memo[key] = out; return out
def nf(f, ep):
    out = {}
    for w, c in f.items():
        for v, d in nf_word(w, ep).items(): acc(out, v, kmul(c, d))
    return out
# ---------------- E. structural conditions on leading words and eliminations ----------------
badE = sum(1 for q in RULES if any(a in ELIM or s_(a) in KILLED or t_(a) in KILLED for a in q))
badE2 = 0
for a, r in ELIM.items():
    if s_(a) in KILLED or t_(a) in KILLED:
        if nf(r, (t_(a), s_(a))): badE2 += 1
res['E_leads_with_eliminated_or_dead_arrows'] = badE; res['E_dead_eliminations_not_zero'] = badE2; log('E', badE, badE2)
# ---------------- B. generators reduce to zero ----------------
badB = 0
for n, (ep, origin, row) in enumerate(D['ROWS']):
    if nf({p: kconv(c) for p, c in row.items()}, ep): badB += 1
    if n % 5000 == 0: log('B', n, badB)
res['B_generators_not_reducing_to_zero'] = badB; log('B done', badB)
# ---------------- C. overlaps ----------------
badC = 0; nC = 0
for q1, r1 in RULES.items():
    for k in range(1, len(q1)):
        suf = q1[k:]
        for q2 in LEADS_BY_FIRST.get(suf[0], ()):
            if len(q2) > len(suf) and q2[:len(suf)] == suf:
                nC += 1
                ep = (t_(q1[0]), s_(q2[-1]))
                tail = q2[len(suf):]; head = q1[:k]
                left = nf({u + tail: c for u, c in r1.items()}, ep)
                right = nf({head + u: c for u, c in RULES[q2].items()}, ep)
                diff = dict(left)
                for w, c in right.items(): acc(diff, w, kmul(KMONE, c))
                if diff: badC += 1
    if nC and nC % 20000 < 40: pass
res['C_overlaps'] = nC; res['C_unresolved'] = badC; log('C', nC, badC)
# ---------------- D. inclusions ----------------
badD = 0; nD = 0
for q1, r1 in RULES.items():
    for q2, r2 in RULES.items():
        if q2 != q1 and len(q2) <= len(q1):
            for i in range(len(q1) - len(q2) + 1):
                if q1[i:i + len(q2)] == q2:
                    nD += 1
                    ep = (t_(q1[0]), s_(q1[-1]))
                    left = nf(r1, ep)
                    right = nf({q1[:i] + u + q1[i + len(q2):]: c for u, c in r2.items()}, ep)
                    diff = dict(left)
                    for w, c in right.items(): acc(diff, w, kmul(KMONE, c))
                    if diff: badD += 1
res['D_inclusions'] = nD; res['D_unresolved'] = badD; log('D', nD, badD)
# ---------------- F. irreducible paths ----------------
LEADS = set(RULES)
MAXL = max(len(q) for q in LEADS)
def irreducible(w): return not any(w[i:i + L] in LEADS for L in range(2, MAXL + 1) for i in range(len(w) - L + 1))
layer = [(a,) for a in sorted(ACTIVE)]
counts = []
while layer and len(counts) < 10:
    counts.append(len(layer))
    layer = [w + (a,) for w in layer for a in sorted(ACTIVE) if s_(w[-1]) == t_(a) and irreducible(w + (a,))]
counts.append(len(layer))
res['F_live_vertices'] = len(VERTS); res['F_irreducible_by_length'] = counts; res['F_dimension'] = len(VERTS) + sum(counts)
log('F', counts, res['F_dimension'])
# ---------------- G. integrality ----------------
nonint = sum(1 for r in list(RULES.values()) + list(ELIM.values()) for c in r.values() if not den_prime_to_p(c))
res['G_non_integral'] = nonint; log('G', nonint)
# ---------------- H. comparison with the modular program of Article I ----------------
M = pickle.load(open(ZE + '/specfib/z4_upper_algebra_modp.pkl', 'rb'))
MR = M['rules']
same_active = sorted(M['active']) == sorted(ACTIVE); same_verts = sorted(M['verts']) == sorted(VERTS)
same_leads = set(MR) == set(RULES)
diffH = 0
if same_leads:
    for q, r in RULES.items():
        a = {w: kred(c) for w, c in r.items() if kred(c)}
        b = {w: int(c) % P for w, c in MR[q].items() if int(c) % P}
        if a != b: diffH += 1
res['H_same_active'] = same_active; res['H_same_vertices'] = same_verts; res['H_same_leads'] = same_leads
res['H_rules_with_different_reduction'] = diffH; log('H', same_active, same_verts, same_leads, diffH)
json.dump(res, open('/home/claude/hj/work/verif/verif_exact.json', 'w'), indent=1)
log('done', res)
